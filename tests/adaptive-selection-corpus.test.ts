/**
 * The selection corpus: twelve windows, and the *decision* recorded for each.
 *
 * `tests/fixtures/selection/` is the fifth corpus. The other four record what a
 * layout **is**; this one records why it was chosen — the full ranking, every
 * loser's cost, and the runner-up. The difference matters when a threshold moves:
 * the audit would show that some number changed, this shows that a decision
 * changed, which is the thing a reviewer actually needs to approve.
 *
 * The generator (`scripts/gen-selection-fixtures.ts`) writes the files, and its
 * `--check` mode is the same check `npm run check` runs. This file is the part
 * that belongs in the suite: the snapshots must agree with `selectBest()` *now*,
 * so a corpus that was regenerated but never reviewed still fails as soon as the
 * decision inside it stops being the decision the code makes.
 */
import { describe, expect, it } from "vitest";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

import { CORPUS, WINDOWS, snapshot } from "../scripts/gen-selection-fixtures";
import { REPAIR_LADDER } from "../src/components/menu/adaptive/repair";

const ROOT = join(__dirname, "..");
const DIR = join(ROOT, CORPUS);

function files(): string[] {
  return existsSync(DIR) ? readdirSync(DIR).filter((f) => f.endsWith(".json")).sort() : [];
}

describe("the selection corpus", () => {
  it("holds one file per window, and nothing else", () => {
    expect(files()).toEqual(WINDOWS.map((w) => `${w.id}.json`).sort());
  });

  it("states what selectBest decides today", () => {
    for (const window of WINDOWS) {
      const actual = readFileSync(join(DIR, `${window.id}.json`), "utf8");
      const want = JSON.stringify(snapshot(window), null, 1) + "\n";
      expect(actual, `${window.id} is stale — re-run npm run gen:select`).toBe(want);
    }
  });

  it("never records a broken window", () => {
    for (const window of WINDOWS) {
      const data = JSON.parse(readFileSync(join(DIR, `${window.id}.json`), "utf8")) as {
        ok: boolean;
        chosen: string;
        shippedIsBest: boolean;
      };
      expect(data.ok, window.id).toBe(true);
      expect(data.chosen, window.id).toBe("as-planned");
      expect(data.shippedIsBest, window.id).toBe(true);
    }
  });

  it("ranks every rung, and says which one came second", () => {
    for (const window of WINDOWS) {
      const data = JSON.parse(readFileSync(join(DIR, `${window.id}.json`), "utf8")) as {
        ranked: string[];
        losers: number;
        runnerUp: string | null;
      };
      expect(data.ranked, window.id).toHaveLength(REPAIR_LADDER.length);
      expect(data.losers, window.id).toBe(REPAIR_LADDER.length - 1);
      expect(data.runnerUp, window.id).toBe(REPAIR_LADDER[1].id);
    }
  });

  it("explains itself: every row carries the window's reason for being here", () => {
    for (const window of WINDOWS) {
      const data = JSON.parse(readFileSync(join(DIR, `${window.id}.json`), "utf8")) as {
        why: string;
        window: string;
      };
      expect(data.why.length, window.id).toBeGreaterThan(20);
      expect(data.window, window.id).toBe(`${window.width}×${window.height}`);
    }
  });

  it("spans the corners of the space, not a line through the middle", () => {
    const widths = WINDOWS.map((w) => w.width);
    const heights = WINDOWS.map((w) => w.height);
    expect(Math.min(...widths)).toBeLessThanOrEqual(320);
    expect(Math.max(...widths)).toBeGreaterThanOrEqual(3840);
    expect(Math.min(...heights)).toBeLessThanOrEqual(320);
    expect(Math.max(...heights)).toBeGreaterThanOrEqual(2160);
  });

  it("has no two windows with the same shape", () => {
    const shapes = new Set(WINDOWS.map((w) => `${w.width}×${w.height}`));
    expect(shapes.size).toBe(WINDOWS.length);
    const ids = new Set(WINDOWS.map((w) => w.id));
    expect(ids.size).toBe(WINDOWS.length);
  });

  it("records a profile a renderer could paint", () => {
    for (const window of WINDOWS) {
      const data = JSON.parse(readFileSync(join(DIR, `${window.id}.json`), "utf8")) as {
        profile: Record<string, number | string | boolean>;
        score: Record<string, number>;
      };
      for (const [key, value] of Object.entries(data.profile)) {
        if (typeof value === "number") expect(Number.isFinite(value), `${window.id} ${key}`).toBe(true);
      }
      for (const [key, value] of Object.entries(data.score)) {
        expect(Number.isFinite(value), `${window.id} score.${key}`).toBe(true);
        expect(value, `${window.id} score.${key}`).toBeGreaterThanOrEqual(0);
      }
    }
  });

  it("is regenerated by a script that can say so", () => {
    /* `--check` is the contract `npm run check` relies on; it must exist. */
    const src = readFileSync(join(ROOT, "scripts/gen-selection-fixtures.ts"), "utf8");
    expect(src).toContain('process.argv.includes("--check")');
    expect(src).toContain("stale ");
  });
});
