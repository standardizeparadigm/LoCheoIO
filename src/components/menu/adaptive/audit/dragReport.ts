/**
 * The drag audit, as Markdown — `docs/adaptive-drag.md`.
 *
 * WHY A SECOND GENERATED REPORT
 * -----------------------------
 * `docs/adaptive-audit.md` is a table of 578 *windows*, and every row of it is
 * true at every moment. The thing this report adds is time: a drag is a sequence,
 * and the band's whole value is a property of the sequence — the same windows,
 * visited in a different order, produce a different number of rebuilds.
 *
 * A checked-in report rather than only a script, for the same reason the audit
 * has one: the question "what did the layout do when we shipped 1.1.8" survives
 * the release, and `--check` re-renders it byte for byte so it cannot rot.
 *
 * WHY TWO COLUMNS AND NOT ONE
 * ---------------------------
 * A monotone sweep crosses each boundary once, so a step function also changes
 * the rung once: on a sweep the band saves almost nothing. On a pointer that
 * shakes by a pixel — the gesture the band exists for — it saves everything.
 * Printing one number would let the report claim either story; printing both
 * makes the difference the point.
 */
import type { DragPath, DragReport } from "./drag";
import { auditWindows } from "./audit";
import { HYSTERESIS_MARGIN } from "../hysteresis";

/** Width of the bar column, in characters. */
const BAR = 32;

function bar(count: number, max: number): string {
  if (max <= 0) return "";
  /* A zero renders as an empty track, not as one block: the bar is a share. */
  if (count <= 0) return "·".repeat(BAR);
  return "█".repeat(Math.max(1, Math.round((count / max) * BAR))).padEnd(BAR, "·");
}

const pct = (share: number, total: number) =>
  total <= 0 ? "—" : `${Math.round((share / total) * 100)}%`;

/** One row per drag. */
function table(paths: DragPath[]): string {
  const head = [
    "| drag | height | widths | sweep raw → held | shake raw → held | boundaries | lag | contract |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  const max = paths.reduce((m, p) => Math.max(m, p.ditherRaw), 0);
  const rows = paths.map((p) => {
    const sweep = `${p.changesRaw} → ${p.changesHeld}`;
    const shake = `${String(p.ditherRaw).padStart(2)} → ${p.ditherHeld} ${bar(p.ditherRaw, max)}`;
    const contract = p.violations ? `✗ ${p.violations}` : "ok";
    return `| \`${p.label}\` | ${p.height} | ${p.from}–${p.to} | ${sweep} | ${shake} | ${p.boundaries} | ${p.worstLag}px | ${contract} |`;
  });
  return [...head, ...rows].join("\n");
}

/** The whole document. Generated; never edited by hand. */
export function renderDragMarkdown(r: DragReport): string {
  const savedSweep = r.changesRaw - r.changesHeld;
  const savedShake = r.ditherRaw - r.ditherHeld;
  return `# Drag audit — ${r.paths.length} drags, ${r.steps} windows

> Generated by \`npm run audit:drag -- --write\`. \`npm run check\` re-renders it and
> fails if this file differs by a byte, so the numbers below are never older than
> the code that produced them.

The window audit in \`adaptive-audit.md\` resolves ${auditWindows().length} windows and
checks the contract on each; every one of them is a legal layout. This report asks
the other question: **when the window moves, how often does the screen rebuild?**

## What was replayed

For each of the ${r.paths.length} presets, two gestures at the preset's own height:

- **sweep** — the width walked in 1px steps, from 120px left of the preset to 120px
  right. This is a drag: monotone, and every boundary is crossed once.
- **shake** — a pointer that settles near a boundary and moves by a pixel:
  \`b−1, b, b+1, b\`, twice, at each boundary inside the swept range. This is a
  trackpad drifting under a still finger, and it is the gesture the two-pixel band
  was built for.

Both are replayed twice: once as \`resolveAdaptive()\` returns them (**raw**), once
through the chain \`useAdaptive()\` paints (**held**).

## Totals

| gesture | raw | held | saved |
| --- | --- | --- | --- |
| sweep, ${r.steps} windows | ${r.changesRaw} | ${r.changesHeld} | ${savedSweep} (${pct(savedSweep, r.changesRaw)}) |
| shake, ${r.boundaries} boundaries | ${r.ditherRaw} | ${r.ditherHeld} | ${savedShake} (${pct(savedShake, r.ditherRaw)}) |

- **Held frames:** ${r.heldFrames} of ${r.steps} (${pct(r.heldFrames, r.steps)}) — the layout is
  deliberately stale for that share of a drag, and never by more than ${r.worstLag}px.
- **Contract:** ${r.violations} violations across every painted profile. A held profile is a
  *previous* profile, so it was legal when it was painted and stays legal here.
- **Stalled:** ${r.stalled.length} of ${r.paths.length} paths held longer than \`HYSTERESIS_MARGIN + 1\`
  frames, which is the bound: the band releases as soon as the window is more than
  ${HYSTERESIS_MARGIN}px past the edge, so a longer run would be a stabiliser that latches.

### Why the sweep saves so little

A drag crosses each boundary once and a step function changes the rung once. There
is nothing to suppress. This report is not hiding that: **${savedSweep} change in
${r.changesRaw}** on a sweep is the honest number, and it is why the band is
documented as a fix for jitter rather than for dragging.

## Per drag

${table(r.paths)}

## Reading it

- A **shake** column that is not zero means the band leaks: the pointer moved inside
  the margin and the rung still changed.
- A **lag** above \`HYSTERESIS_MARGIN\` means the band leaks the other way and paints a
  profile from a window it does not belong to.
- A **contract** column that is not \`ok\` means \`stabilize()\` produced something the
  invariants reject — the one failure that would make the band unsafe rather than
  merely late.
`;
}
